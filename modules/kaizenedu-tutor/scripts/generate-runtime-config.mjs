#!/usr/bin/env node
/**
 * Bake the product's non-secret configuration into the server bundle at build
 * time.
 *
 * Vercel populates `process.env` from its own project settings and from
 * nothing else. A `.env` committed to the repository is not read, even when it
 * is traced into the function bundle: `instrumentation.ts` tried exactly that
 * and the values never arrived, because a serverless function's working
 * directory is not the project root the trace was written relative to. The
 * symptom was a tutor that would not start — `DEFAULT_MODEL` sat in `.env`
 * while the runtime saw nothing, and `/api/tutor/health` reported the model as
 * `built-in` on a deploy whose `.env` clearly named one.
 *
 * A build step has no such problem. `next build` runs at the repository root,
 * so this reads `.env` there and writes the values into a module compiled into
 * the server bundle like any other code. Import it and they are present,
 * whatever the runtime's working directory turns out to be and whichever
 * bundler produced the build.
 *
 * THIS FILE DELIBERATELY CARRIES NO SECRETS. Only `.env` is read — the tracked,
 * non-secret file — and `DENY` below rejects anything shaped like a
 * credential even if one is added there by mistake. `.env.local` is never
 * opened. Provider API keys belong in the host's environment variables, where
 * they can be rotated without a redeploy and never enter a build artifact;
 * `docs/DO-THIS-NEXT.md` names the three the tutor needs.
 *
 * The host still wins. Anything already in `process.env` at runtime — a Vercel
 * project variable — is left alone, so moving a value into the dashboard
 * overrides the baked copy with no code change.
 */
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';

const ROOT = process.cwd();
const SOURCE = join(ROOT, '.env');
const OUT = join(ROOT, 'lib', 'server', 'runtime-config.generated.ts');

/**
 * What may be baked: the product's own switches and dials, by exact name or by
 * a prefix ending in `_`. Anything not named here stays where it is.
 */
const ALLOW = [
  'TUTOR_MODE',
  'TUTOR_STAFF_EMAILS',
  'TUTOR_TTS_PROVIDER',
  'TUTOR_TTS_VOICE',
  'TUTOR_ASR_PROVIDER',
  'TUTOR_DAILY_CAP_CENTS',
  'TUTOR_PRICING_JSON',
  'TUTOR_BAND_MODEL_ROUTES',
  'NEXT_PUBLIC_TUTOR_MODE',
  'DEFAULT_MODEL',
  'MODEL_ROUTES',
];

/**
 * A second fence, independent of the first. Even a name on the allowlist is
 * refused if it looks like a credential, so a future edit to `.env` cannot
 * quietly put a secret into a build artifact by adding one line.
 */
const DENY = /(_API_KEY|_SECRET|_TOKEN|_PASSWORD|_ACCESS_KEY|DATABASE_URL)$/;

function allowed(key) {
  if (DENY.test(key)) return false;
  return ALLOW.some((entry) => (entry.endsWith('_') ? key.startsWith(entry) : key === entry));
}

function parseEnvFile(file) {
  const out = {};
  if (!existsSync(file)) return out;
  for (const raw of readFileSync(file, 'utf8').split('\n')) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq <= 0) continue;
    const key = line.slice(0, eq).trim();
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(key) || !allowed(key)) continue;
    let value = line.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    if (value) out[key] = value;
  }
  return out;
}

const values = parseEnvFile(SOURCE);
const keys = Object.keys(values).sort();

const body = `/**
 * GENERATED by scripts/generate-runtime-config.mjs during \`next build\`.
 * Do not edit; your change will be overwritten by the next build.
 *
 * These are the product's non-secret defaults, read from the tracked \`.env\`
 * at build time because a serverless runtime does not read repo dotfiles. The
 * generator refuses anything shaped like a credential, so nothing here is a
 * secret — provider keys live in the host's environment variables.
 *
 * Importing this module applies the values, except under test, where it is
 * inert so a suite sees the environment it set up rather than this
 * deployment's. A variable the host already set is never overwritten, so a
 * Vercel project variable always wins.
 */
const BAKED: Readonly<Record<string, string>> = Object.freeze(${JSON.stringify(values, null, 2)});

/** Names baked into this build, for diagnostics. */
export const BAKED_KEYS: readonly string[] = Object.freeze(${JSON.stringify(keys)});

let applied = false;

/** Idempotent: fills only the variables the host left unset or empty. */
export function applyBakedConfig(): void {
  if (applied) return;
  applied = true;
  for (const [key, value] of Object.entries(BAKED)) {
    if (process.env[key] === undefined || process.env[key] === '') {
      process.env[key] = value;
    }
  }
}

// Applying on import is skipped under test, for the same reason
// tests/setup-env.ts refuses to load .env.local: a suite must see the
// environment it set up, not whatever this deployment happens to be configured
// with. Importing this module from a test is inert; call applyBakedConfig()
// to exercise it deliberately.
if (!process.env.VITEST && process.env.NODE_ENV !== 'test') {
  applyBakedConfig();
}
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, body);
console.log(
  `[runtime-config] baked ${keys.length} non-secret variable${keys.length === 1 ? '' : 's'}: ${keys.join(', ') || '(none)'}`,
);
